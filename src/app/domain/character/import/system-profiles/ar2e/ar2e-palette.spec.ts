/**
 * 架空のシートを変え、チャットパレットの文を書く。
 *
 * @param changes 架空のシートを変える道具（かける順）
 * @returns チャットパレットの文
 */
const paletteOf = (...changes: SheetChange[]): string => {
  const character = ar2eCharacterOf(sheetWith(...changes));
  return writeAr2ePalette(placeSkills(character.skills), planAttacks(character.hands, character.handedness));
};

/**
 * パレットから、見出しの下の送れる行を取り出す。見出しと空行は、アプリのパレットの欄と同じ見分け方（`paletteCommandGroups`）で分ける。
 *
 * @param palette パレットの文
 * @param heading 見出し
 * @returns 見出しの下の送れる行。見出しがなければ空
 */
const blockOf = (palette: string, heading: string): string[] =>
  paletteCommandGroups(palette.split('\n')).find((group) => group.heading === heading)?.lines ?? [];

