describe('取り込んだコマのチャットパレット（仕様書「取り込んだコマのチャットパレット」「判定の見出しのかたまり」「受動判定の見出しのかたまり」「リソース操作の見出しのかたまり」「バフ操作の見出しのかたまり」「バッドステータスの行」「パレットのスキルの見出しのかたまり」「スキルの説明の行」）', () => {
  it('架空のキャラクターのパレットは、仕様書のとおりの形', () => {
    expect(paletteOf()).toBe(BASE_PALETTE);
  });

  it('スキルが 1 つもなければ、スキルの見出しのかたまりを作らない', () => {
    const palette = paletteOf(withSkills());
    expect(palette).not.toContain('スキル');
    expect(palette.endsWith('ダメージ≪試しの短剣≫(左手)')).toBe(true);
  });
});

describe('能動判定の見出しのかたまり（仕様書「能動判定の見出しのかたまり」「能動判定の手の組み合わせ」）', () => {
  it('合計しないで、右手に武器、左手に盾: 右手の行だけ', () => {
    expect(blockOf(paletteOf(withHandedness('1'), withHands(SWORD, SHIELD)), '能動判定')).toEqual([
      '{命中ダイス}D6+{右手命中}>? 命中判定≪ロングソード≫(右手)',
      '{攻撃ダイス}D6+{右手攻撃力} ダメージ≪ロングソード≫(右手)',
    ]);
  });

  it('合計しないで、武器がない: 合計の 1 組（武器名なし）', () => {
    expect(blockOf(paletteOf(withHandedness(null), withHands(EMPTY_HAND, SHIELD)), '能動判定')).toEqual([
      '{命中ダイス}D6+{命中}>? 命中判定',
      '{攻撃ダイス}D6+{攻撃力} ダメージ',
    ]);
  });

  it('両手を合計: 合計の 1 組。武器名は、武器を持つ手の名前を右手、左手の順に', () => {
    expect(blockOf(paletteOf(withHandedness('2'), withHands(SWORD, DAGGER)), '能動判定')).toEqual([
      '{命中ダイス}D6+{命中}>? 命中判定≪ロングソード≫≪ダガー≫',
      '{攻撃ダイス}D6+{攻撃力} ダメージ≪ロングソード≫≪ダガー≫',
    ]);
  });

  it('命中のみ合計: 命中判定は合計、ダメージは右手と左手', () => {
    expect(blockOf(paletteOf(withHandedness('3'), withHands(SWORD, SHIELD)), '能動判定')).toEqual([
      '{命中ダイス}D6+{命中}>? 命中判定≪ロングソード≫',
      '{攻撃ダイス}D6+{右手攻撃力} ダメージ≪ロングソード≫(右手)',
      '{攻撃ダイス}D6+{左手攻撃力} ダメージ(左手)',
    ]);
  });

  it('全部表示: 右手、左手、合計', () => {
    expect(blockOf(paletteOf(withHandedness('4'), withHands(SWORD, SHIELD)), '能動判定')).toEqual([
      '{命中ダイス}D6+{右手命中}>? 命中判定≪ロングソード≫(右手)',
      '{命中ダイス}D6+{左手命中}>? 命中判定(左手)',
      '{命中ダイス}D6+{命中}>? 命中判定≪ロングソード≫',
      '{攻撃ダイス}D6+{右手攻撃力} ダメージ≪ロングソード≫(右手)',
      '{攻撃ダイス}D6+{左手攻撃力} ダメージ(左手)',
      '{攻撃ダイス}D6+{攻撃力} ダメージ≪ロングソード≫',
    ]);
  });
});

describe('スキルの使う行（仕様書「スキルの使う行」「判定が判定の選択肢のスキルの使う行」「判定が命中判定のスキルの使う行」）', () => {
  /**
   * 架空のシートのパレットの「【メジャー】」の見出しの下から、スキルの説明の行を除いた行（使う行）を取り出す。
   *
   * @param changes 架空のシートを変える道具（かける順）
   * @returns メジャーのスキルの使う行
   */
  const skillLines = (...changes: SheetChange[]) =>
    blockOf(paletteOf(...changes), '【メジャー】').filter((line) => !line.startsWith('{スキル/'));

  it('判定が命中判定なら、能動判定の命中判定の行と同じ数だけ、手を付けて作る（武器名は付けない）', () => {
    expect(
      skillLines(
        withHandedness('1'),
        withHands(SWORD, DAGGER),
        withSkills({ Name: 'バッシュ', Timing: 'メジャー', Roll: '命中判定', Cost: '3' })
      )
    ).toEqual([
      '{命中ダイス}D6+{右手命中}>? ≪バッシュ≫(右手) :MP-3LZ',
      '{命中ダイス}D6+{左手命中}>? ≪バッシュ≫(左手) :MP-3LZ',
    ]);
  });

  it('判定が能力値なら能力値判定、回避判定なら回避の振り方', () => {
    expect(
      skillLines(
        withSkills(
          { Name: '力技', Timing: 'メジャー', Roll: '筋力' },
          { Name: '見切り', Timing: 'メジャー', Roll: '回避判定', Cost: '2' }
        )
      )
    ).toEqual(['{筋力判定ダイス}D6+{筋力判定}>=? ≪力技≫', '{回避ダイス}D6+{回避}>=? ≪見切り≫ :MP-2LZ']);
  });

  it('判定が選択肢でなく、コストもないスキルは、使う行を作らない', () => {
    expect(
      skillLines(
        withSkills(
          { Name: '自動', Timing: 'メジャー', Roll: '自動成功' },
          { Name: '対決', Timing: 'メジャー', Roll: '【知力】' },
          { Name: '線', Timing: 'メジャー', Cost: '-' }
        )
      )
    ).toEqual([]);
  });

  it('タイミングに関わらず、判定の行を作る', () => {
    const palette = paletteOf(withSkills({ Name: 'リカバー', Timing: 'リアクション', Roll: '魔術判定', Cost: '2' }));
    expect(blockOf(palette, '【リアクション】')).toEqual([
      '{スキル/リアクション/リカバー}',
      '{魔術判定ダイス}D6+{魔術判定}>=? ≪リカバー≫ :MP-2LZ',
    ]);
  });

  it('スキル名の改行は直さない。行は割れる（仕様書「アックスに載せる文字」）', () => {
    const palette = paletteOf(withSkills({ Name: 'アタック&lt;br&gt;ブレイク', Timing: 'メジャー', Cost: '1' }));
    expect(blockOf(palette, '【メジャー】')).toEqual([
      '{スキル/メジャー/アタック',
      'ブレイク}',
      '≪アタック',
      'ブレイク≫ :MP-1LZ',
    ]);
  });

  it('スキル名の中の / と \\ は、説明の行の参照で逃がす。使う行のスキル名は書かれたまま', () => {
    const palette = paletteOf(withSkills({ Name: 'アタック/ブレイク\\改：弐', Timing: 'メジャー', Cost: '1' }));
    expect(blockOf(palette, '【メジャー】')).toEqual([
      '{スキル/メジャー/アタック\\/ブレイク\\\\改:弐}',
      '≪アタック/ブレイク\\改：弐≫ :MP-1LZ',
    ]);
  });
});
